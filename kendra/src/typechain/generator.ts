import path from 'path'
import fs from 'fs-extra'
import { getTypechainDir } from '../utils/paths'
import { logger } from '../utils/logger'

interface AbiMessage {
  label: string
  mutates: boolean
  args: Array<{ label: string; type: { type: string } }>
  returnType?: { type: string }
}

interface AbiSpec {
  messages: AbiMessage[]
  constructors: Array<{
    label: string
    args: Array<{ label: string; type: { type: string } }>
  }>
}

interface ContractMetadata {
  spec: AbiSpec
  contract: { name: string; version: string }
}

function mapType(inkType: string): string {
  const typeMap: Record<string, string> = {
    u8: 'number',
    u16: 'number',
    u32: 'number',
    u64: 'bigint',
    u128: 'bigint',
    i8: 'number',
    i16: 'number',
    i32: 'number',
    i64: 'bigint',
    i128: 'bigint',
    bool: 'boolean',
    String: 'string',
    AccountId: 'string',
    Balance: 'bigint',
    Hash: 'string',
    '()': 'void',
  }
  return typeMap[inkType] ?? 'unknown'
}

function capitalise(str: string): string {
  return str.charAt(0).toUpperCase() + str.slice(1)
}

function camelCase(str: string): string {
  return str.replace(/_([a-z])/g, (_, letter: string) => letter.toUpperCase())
}

export async function generateTypechain(
  contractName: string,
  metadataPath: string,
): Promise<void> {
  const metadata: ContractMetadata = await fs.readJson(metadataPath)

  const className = capitalise(camelCase(contractName))
  const typechainDir = getTypechainDir()
  await fs.ensureDir(typechainDir)

  const messages = metadata.spec.messages ?? []
  const constructors = metadata.spec.constructors ?? []

  const queryMethods = messages
    .filter(m => !m.mutates)
    .map(m => {
      const params = m.args
        .map(a => `${camelCase(a.label)}: ${mapType(a.type.type)}`)
        .join(', ')
      const returnType = m.returnType ? mapType(m.returnType.type) : 'void'
      return `  ${camelCase(m.label)}(${params}): Promise<${returnType}>`
    })
    .join('\n')

  const txMethods = messages
    .filter(m => m.mutates)
    .map(m => {
      const params = m.args
        .map(a => `${camelCase(a.label)}: ${mapType(a.type.type)}`)
        .join(', ')
      return `  ${camelCase(m.label)}(${params}): Promise<TxResult>`
    })
    .join('\n')

  const constructorParams =
    constructors[0]?.args
      .map(a => `${camelCase(a.label)}: ${mapType(a.type.type)}`)
      .join(', ') ?? ''

  const output = `// Auto-generated by Kendra
// Contract: ${contractName} v${metadata.contract.version}
// Do not edit manually — regenerate with: kendra compile

import type { TxResult } from '@awarizon/core'

export interface ${className}Query {
${queryMethods || '  // No query methods'}
}

export interface ${className}Tx {
${txMethods || '  // No tx methods'}
}

export interface ${className} {
  address: string
  query: ${className}Query
  tx: ${className}Tx
}

export interface ${className}DeployResult {
  contract: ${className}
  address: string
  hash: string
  blockNumber: number
}

export type Deploy${className} = (
  params: { ${constructorParams} },
  options?: { gasLimit?: bigint; value?: bigint }
) => Promise<${className}DeployResult>
`

  const outPath = path.join(typechainDir, `${className}.ts`)
  await fs.writeFile(outPath, output)

  logger.success(`TypeChain: typechain/${className}.ts`)
}
